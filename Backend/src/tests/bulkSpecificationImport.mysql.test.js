'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const mysql = require('mysql2/promise');
const ExcelJS = require('exceljs');

const socket = process.env.BULK_SPEC_FIXTURE_SOCKET;
test('Standard import commits common and variant values together with prices and receipts, and physically rolls back a failed product', { skip: !socket }, async t => {
    const database = 'sw_standard_specs_' + randomUUID().replaceAll('-', '');
    const admin = await mysql.createConnection({ user:'root',socketPath:socket });
    await admin.query('CREATE DATABASE ' + database);
    process.env.NODE_ENV = 'test';
    const cfg = require('../config/sequelize-config').test;
    Object.assign(cfg, { database,username:'root',password:'',logging:false,dialectOptions:{socketPath:socket} });
    const fs = require('node:fs/promises'), path = require('node:path');
    const uploads = await fs.mkdtemp(path.join(require('node:os').tmpdir(), 'sw-colour-images-'));
    process.env.UPLOAD_ROOT = uploads;
    t.after(() => fs.rm(uploads, {recursive:true,force:true}));
    const db = require('../models');
    t.after(async () => { await db.sequelize.close(); await admin.query('DROP DATABASE ' + database); await admin.end(); });
    await db.sequelize.sync();
    await db.sequelize.query('CREATE TABLE item_code_sequences (id INT PRIMARY KEY, sequence_name VARCHAR(50) UNIQUE, last_number INT, updated_at DATETIME)');
    await db.sequelize.query("INSERT INTO item_code_sequences VALUES (1,'item',0,NOW())");
    const type = await db.ItemType.create({name:'Laptop RAM',code:'RAM'});
    await db.Category.create({name:'Components',code:'COMP'});
    await db.Brand.create({name:'Fixture',code:'FX'});
    await db.InventoryLocation.create({name:'Store',code:'ST',location_type:'online'});
    const memory = await db.ItemSpecification.create({name:'Memory Type',code:'MEM',data_type:'select',options:['DDR4','DDR5']});
    const capacity = await db.ItemSpecification.create({name:'Capacity',code:'CAP',data_type:'number'});
    for (const spec of [memory,capacity]) await db.ItemTypeSpecification.create({item_type_id:type.id,specification_id:spec.id});
    const service = require('../services/bulkProductImportService');
    const book = new ExcelJS.Workbook(); await book.xlsx.load(await service.template());
    const products = book.getWorksheet('Products'), variants = book.getWorksheet('Variants'), facts = book.getWorksheet('Specifications');
    products.getRow(2).values=['Module', 'Components', 'Fixture', 'Laptop\u00a0RAM', '', '', 'New', 0.1];
    products.getRow(3).values=['Upgrade', 'Components', 'Fixture', 'Laptop RAM', '', '', 'New', 0.1];
    variants.getRow(2).values=['Module','Basic',5,10,10,10,10,10,1,0,'Store',null,null,'Black','#000000','White','#ffffff'];
    variants.getRow(3).values=['Upgrade','Kit',6,20,20,20,20,20,2,0,'Store',null,null,'Black','#000000'];
    variants.getRow(4).values=['Module','Plus',7,15,15,15,15,15,3,0,'Store',null,null,'Black','#000000'];
    facts.getRow(2).values=['Module','','Memory Type','DDR4'];
    facts.getRow(3).values=['Module','Plus','Capacity',16];
    facts.getRow(4).values=['Upgrade','','Memory Type','DDR5'];
    const bytes = await book.xlsx.writeBuffer();
    const parsed = await service.parseAndValidate(bytes);
    assert.deepEqual(service.summary(parsed).workbookErrors, []);
    db.InventoryStockMovement.addHook('afterCreate','failSecondProduct', movement => {
        if (String(movement.notes).includes('SW-000002')) throw new Error('Fixture failure after opening receipt');
    });
    const first = await service.importProducts(bytes, null);
    assert.equal(first.imported,1); assert.equal(first.failed,1);
    assert.equal(first.results[1].rowNumber,3);
    for (const [name,count] of Object.entries({Item:1,ItemVariant:2,ItemPrice:4,ItemPaymentPrice:8,ItemSpecificationValue:1,ItemColor:2,ItemVariantColor:3,InventoryStock:2,InventoryStockMovement:2})) assert.equal(await db[name].count(),count,name);
    assert.equal((await db.ItemVariant.findOne({where:{variant_name:'Plus'}})).attributes.Capacity, '16');
    assert.deepEqual((await db.ItemVariant.findOne({where:{variant_name:'Basic'}})).attributes,{});
    assert.equal((await db.ItemSpecificationValue.findOne()).value,'DDR4');
    db.InventoryStockMovement.removeHook('afterCreate','failSecondProduct');
    assert.equal((await service.importProducts(bytes,null,{},[3])).imported,1);
    assert.equal(await db.Item.count(),2); assert.equal(await db.InventoryStockMovement.count(),3);
    const upgrade=await db.Item.findOne({where:{item_name:'Upgrade'}});
    assert.equal((await db.ItemSpecificationValue.findOne({where:{item_id:upgrade.id}})).value,'DDR5');
    const moduleItem = await db.Item.findOne({where:{item_name:'Module'}});
    const basic = await db.ItemVariant.findOne({where:{variant_name:'Basic'}});
    assert.equal(basic.variant_sku,'SWV-000001-BasicBlackWhite');
    const blacks = await db.ItemColor.findAll({where:{hex_code:'#000000'}});
    assert.equal(blacks.length,2);
    assert.equal(new Set(blacks.map(c=>String(c.item_id))).size,2);
    assert.equal(await db.ItemVariantColor.count(),4);
    async function get(controller,params) {
        let data;
        await controller({params}, {status(code){assert.equal(code,200);return this;},json(body){data=body.data;}});
        return data;
    }
    const adminColors = await get(require('../controllers/itemVariantController').getVariantColors,{id:moduleItem.id,variantId:basic.id});
    assert.deepEqual(adminColors.map(c=>c.hex_code).sort(),['#000000','#FFFFFF']);
    assert.ok(adminColors.every(c=>String(c.item_id)===String(moduleItem.id)));
    await fs.copyFile(path.resolve(__dirname,'../../../Frontend/Admin/public/SWfavicon.png'),path.join(uploads,'fixture.png'));
    await db.ItemImage.create({item_id:moduleItem.id,file_name:'fixture.png',file_path:'fixture.png',is_primary:true});
    const store = await get(require('../controllers/storeProductController').getStoreProductVariants,{id:moduleItem.id});
    const { variantColors, buildVariantChoices, chooseOption } = await import('../../../Frontend/Customer/src/utils/variantSelection.js');
    const publicBasic = store.find(v=>v.variant_sku===basic.variant_sku);
    assert.deepEqual(variantColors(publicBasic).map(c=>c.hex).sort(),['#000000','#FFFFFF']);
    const choice = buildVariantChoices(store).choices.find(c => c.options.some(o => o.id === String(basic.id)));
    assert.equal(chooseOption(choice, 'White').sku, basic.variant_sku);
    await capacity.update({is_active:false});
    assert.ok(service.summary(await service.parseAndValidate(bytes)).workbookErrors.some(e=>e.sheet==='Specifications' && e.rowNumber===3 && e.column==='Specification'));
});
